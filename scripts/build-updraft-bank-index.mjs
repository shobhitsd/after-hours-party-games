// Regenerates lib/updraft-bank/index.js from the category files in that folder.
// Run after adding or removing a category: `npm run build:bank`.
import {readdir,writeFile} from 'node:fs/promises';
const dir=new URL('../lib/updraft-bank/',import.meta.url);
// The ten original categories stay first so deterministic test deals remain readable.
const first=['fruit','animal','country','instrument','bird','flower','vegetable','food','sport','color'];
const ids=(await readdir(dir)).filter(n=>n.endsWith('.js')&&n!=='index.js').map(n=>n.slice(0,-3)).sort();
const ordered=[...first.filter(id=>ids.includes(id)),...ids.filter(id=>!first.includes(id))];
const name=id=>'c_'+id;
await writeFile(new URL('index.js',dir),'// Generated by scripts/build-updraft-bank-index.mjs — do not edit by hand.\n'+ordered.map(id=>`import ${name(id)} from './${id}.js';`).join('\n')+`\nexport default [${ordered.map(name).join(',')}];\n`);
console.log(`Indexed ${ordered.length} Updraft categories.`);
